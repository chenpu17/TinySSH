//! 契约代码生成 PoC（仅 `--features ts` 编译）。
//!
//! 渲染逻辑放库里，生成 example 与新鲜度测试共用，避免两处漂移。

use crate::{AuthDraft, AuthType, Charset, Host, HostDraft};
use ts_rs::{Config, TS};

/// 生成 `ui/src/adapter/generated/wire.generated.ts` 的完整内容。
pub fn render_wire_bindings() -> String {
    // 与本项目现有 wire.ts 口径一致：u64/i64 用 number（不是 bigint）。
    // 用确定性配置（不读环境变量），保证生成物与新鲜度测试可复现。
    let cfg = Config::new().with_large_int("number");
    let decls = [
        ("AuthType", AuthType::decl(&cfg)),
        ("Charset", Charset::decl(&cfg)),
        ("AuthDraft", AuthDraft::decl(&cfg)),
        ("Host", Host::decl(&cfg)),
        ("HostDraft", HostDraft::decl(&cfg)),
    ];

    let mut out = String::from(
        "// @generated by `cargo run -p session-api --features ts --example export-wire`\n\
         // 请勿手改；源类型在 crates/session-api/src/lib.rs。\n\
         // 当前覆盖 Host/HostDraft/AuthDraft/AuthType/Charset；其余类型仍以 wire.ts 手写为准。\n\n",
    );
    for (name, decl) in decls {
        out.push_str(&format!("// ---- {name} ----\n"));
        out.push_str("export ");
        out.push_str(&decl);
        out.push_str("\n\n");
    }
    // ts-rs 的声明里可能带行尾空格；统一去掉，保证 `git diff --check` 与
    // 生成物新鲜度测试使用同一份字节。
    let mut normalized = out
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    normalized = normalized.trim_end().to_string();
    normalized.push('\n');
    normalized
}
